/**
 * Automated Boundary Violation Test.
 * RFC-0010 §14 F3: A component directly importing an Infrastructure class
 * MUST fail the CI gate outright.
 *
 * This test:
 * 1. Creates a temporary violating file in presentation/ that imports from infrastructure/.
 * 2. Runs ESLint programmatic API on it.
 * 3. Asserts that ESLint reports a boundary violation error (boundaries/dependencies).
 * 4. Cleans up the temporary file.
 */

import { ESLint } from 'eslint';
import { writeFileSync, unlinkSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, it, expect, afterEach } from 'vitest';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const VIOLATING_FILE = resolve(
  __dirname,
  '../src/presentation/components/_boundary_violation_test_.tsx',
);

const VIOLATING_CONTENT = `
// INTENTIONAL VIOLATION: presentation importing infrastructure directly.
// This file is auto-generated by the boundary test and will be cleaned up.
import { CryptoWorkerBridge } from '../../infrastructure/crypto/bridge';
export const bridge = new CryptoWorkerBridge();
`;

describe('ESLint Boundary Enforcement (RFC-0010 §14 F3)', () => {
  afterEach(() => {
    // Clean up the violating file
    if (existsSync(VIOLATING_FILE)) {
      unlinkSync(VIOLATING_FILE);
    }
  });

  it('should reject presentation → infrastructure imports', async () => {
    // Create the violating file
    writeFileSync(VIOLATING_FILE, VIOLATING_CONTENT, 'utf-8');

    const eslint = new ESLint();
    const results = await eslint.lintFiles([VIOLATING_FILE]);

    expect(results.length).toBe(1);
    expect(results[0].errorCount).toBeGreaterThan(0);

    const boundaryMessages = results[0].messages.filter(
      (m) => m.ruleId === 'boundaries/dependencies',
    );
    expect(boundaryMessages.length).toBeGreaterThan(0);
    expect(boundaryMessages[0].message).toContain('presentation');
    expect(boundaryMessages[0].message).toContain('infrastructure');
  }, 180000);
});
