type Client struct {
	identity   domain.VAPIDKeyProvider
	subject    string
	httpClient *http.Client
	logger     *slog.Logger
}

func NewClient(identity domain.VAPIDKeyProvider, subject string, timeout time.Duration, logger *slog.Logger) *Client {
	return &Client{
		identity: identity,
		subject:  subject,
		httpClient: &http.Client{
			Timeout: timeout,
			Transport: &SizeGuardRoundTripper{
				Base: http.DefaultTransport,
			},
		},
		logger: logger,
	}
}

// SendResult classifies the Push Service response (ADR-P9-10).
type SendResult struct {
	StatusCode int
	Stale      bool // true ONLY for 404 / 410 -> caller MUST hard-delete
	Transient  bool
	BodyLen    int
}

// Send encrypts the frozen wake payload and dispatches one push.
func (c *Client) Send(ctx context.Context, sub *domain.PushSubscription, class domain.PushTriggerClass) (SendResult, error) {
	// Parse the endpoint for logging host only.
	u, err := url.Parse(sub.Endpoint)
	if err != nil || u.Host == "" {
		c.logger.Error("invalid push endpoint", "sub_id", sub.ID, "error", err)
		return SendResult{}, domain.NewDomainError(domain.ErrPush003, "invalid push endpoint URL", err)
	}
	endpointHost := u.Host

	// Decode keys (tolerate both padded and unpadded per library requirements,
	// though we enforce strictly 65/16 at the HTTP layer, we re-decode here).
	p256dh, err := base64.RawURLEncoding.DecodeString(sub.P256dhKey)
	if err != nil {
		p256dh, err = base64.URLEncoding.DecodeString(sub.P256dhKey)
		if err != nil {
			c.logger.Error("invalid p256dh_key", "sub_id", sub.ID, "endpoint_host", endpointHost, "error", err)
			return SendResult{}, domain.NewDomainError(domain.ErrPush003, "invalid p256dh_key base64", err)
		}
	}

	auth, err := base64.RawURLEncoding.DecodeString(sub.AuthSecret)
	if err != nil {
		auth, err = base64.URLEncoding.DecodeString(sub.AuthSecret)
		if err != nil {
			c.logger.Error("invalid auth_secret", "sub_id", sub.ID, "endpoint_host", endpointHost, "error", err)
			return SendResult{}, domain.NewDomainError(domain.ErrPush003, "invalid auth_secret base64", err)
		}
	}

	wpSub := &webpush.Subscription{
		Endpoint: sub.Endpoint,
		Keys: webpush.Keys{
			P256dh: base64.RawURLEncoding.EncodeToString(p256dh),
			Auth:   base64.RawURLEncoding.EncodeToString(auth),
		},
	}

	opts := &webpush.Options{
		Subscriber:      c.subject,
		VAPIDPublicKey:  c.identity.PublicKeyBase64URL(),
		VAPIDPrivateKey: c.identity.PrivateKeyBase64URL(),
		TTL:             class.TTLSeconds(),
		Urgency:         webpush.Urgency(class.Urgency()),
		Topic:           "",                            // Empty topic prevents coalescing
		RecordSize:      domain.WebPushRecordSize + 86, // webpush-go expects RecordSize to include the 86-byte header
		HTTPClient:      c.httpClient,
	}

	// Always send the frozen WakePayload.
	resp, err := webpush.SendNotificationWithContext(ctx, []byte(domain.WakePayload), wpSub, opts)
	if err != nil {
		// webpush-go does not return the response object on HTTP error, so we inspect the error.
		// If the error was generated by our SizeGuardRoundTripper:
		var de *domain.DomainError
		if errors.As(err, &de) && de.Code == domain.ErrPush005 {
			c.logger.Error("push encode failed: size mismatch", "class", class, "expected", domain.WebPushRecordSize, "error", err)
			return SendResult{}, de // UseCase will increment PushEncodeFailedTotal
		}

		// Transport error or context canceled. Treat as transient.
		c.logger.Info("push attempt outcome", "status_code", 0, "stale", false, "transient", true)
		c.logger.Error("transient error from webpush-go", "error_class", classifyError(err))
		return SendResult{StatusCode: 0, Transient: true, BodyLen: 0}, nil
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, resp.Body)

	// Classify response per ADR-P9-10
	res := SendResult{StatusCode: resp.StatusCode, BodyLen: domain.WebPushRecordSize} // body len verified by guard

	switch resp.StatusCode {
	case 200, 201, 202, 204:
		// Success
		c.logger.Info("push attempt outcome", "status_code", resp.StatusCode, "stale", false, "transient", false)
		return res, nil
	case 404, 410:
		// Authoritative death
		res.Stale = true
		c.logger.Info("push attempt outcome", "status_code", resp.StatusCode, "stale", true, "transient", false)
		return res, nil
	case 400, 401, 403, 413:
		// Server-side defect
		// The use case will log Error, count, and keep the row.
		c.logger.Info("push attempt outcome", "status_code", resp.StatusCode, "stale", false, "transient", false)
		return res, nil
	case 429, 502, 503, 504:
		// Transient
		res.Transient = true
		c.logger.Info("push attempt outcome", "status_code", resp.StatusCode, "stale", false, "transient", true)
		return res, nil
	default:
		// Any other status -> transient
		res.Transient = true
		c.logger.Info("push attempt outcome", "status_code", resp.StatusCode, "stale", false, "transient", true)
		return res, nil
	}
}

// classifyError maps errors from webpush-go into non-sensitive error classes
// without ever exposing endpoint URLs contained in *url.Error.
func classifyError(err error) string {
	if errors.Is(err, context.Canceled) {
		return "canceled"
	}
	if errors.Is(err, context.DeadlineExceeded) {
		return "timeout"
	}
	var dnsErr *net.DNSError
	if errors.As(err, &dnsErr) {
		return "dns"
	}
	var netErr net.Error
	if errors.As(err, &netErr) && netErr.Timeout() {
		return "timeout"
	}
	return "other"
}
